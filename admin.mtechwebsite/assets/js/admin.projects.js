/**
 * Admin Projects Module JavaScript
 */

document.addEventListener('DOMContentLoaded', function() {
    
    // ----------------------------------------
    // Initialize Projects Module
    // ----------------------------------------
    initProjectForm();
    initGalleryUpload();
    initRichEditor();
    initWireframeInteractions();
    initResultItems();
    
});

// ----------------------------------------
// Project Form Initialization
// ----------------------------------------
function initProjectForm() {
    
    // Tab switching for project form
    const tabButtons = document.querySelectorAll('.project-form-tabs .nav-link');
    const tabPanes = document.querySelectorAll('.tab-pane');
    
    tabButtons.forEach(button => {
        button.addEventListener('click', function(e) {
            e.preventDefault();
            
            // Remove active class from all buttons and panes
            tabButtons.forEach(btn => btn.classList.remove('active'));
            tabPanes.forEach(pane => pane.classList.remove('active', 'show'));
            
            // Add active class to clicked button
            this.classList.add('active');
            
            // Show corresponding tab pane
            const targetId = this.getAttribute('data-bs-target') || this.getAttribute('href');
            const targetPane = document.querySelector(targetId);
            if (targetPane) {
                targetPane.classList.add('active', 'show');
            }
        });
    });
    
    // Auto-generate slug from title
    const titleInput = document.getElementById('title');
    const slugInput = document.getElementById('slug');
    
    if (titleInput && slugInput) {
        titleInput.addEventListener('input', function() {
            if (!slugInput.value || slugInput.dataset.autoGenerated === 'true') {
                const slug = generateSlug(this.value);
                slugInput.value = slug;
                slugInput.dataset.autoGenerated = 'true';
            }
        });
        
        slugInput.addEventListener('input', function() {
            this.dataset.autoGenerated = 'false';
        });
    }
}

// ----------------------------------------
// Gallery Upload Functionality
// ----------------------------------------
function initGalleryUpload() {
    const uploadArea = document.querySelector('.gallery-upload-area');
    const fileInput = document.getElementById('gallery-input');
    const previewContainer = document.querySelector('.gallery-preview');
    
    if (!uploadArea || !fileInput) return;
    
    // Click to upload
    uploadArea.addEventListener('click', function() {
        fileInput.click();
    });
    
    // File selection
    fileInput.addEventListener('change', function(e) {
        handleFileSelect(e.target.files);
    });
    
    // Drag and drop
    uploadArea.addEventListener('dragover', function(e) {
        e.preventDefault();
        this.classList.add('dragover');
    });
    
    uploadArea.addEventListener('dragleave', function(e) {
        e.preventDefault();
        this.classList.remove('dragover');
    });
    
    uploadArea.addEventListener('drop', function(e) {
        e.preventDefault();
        this.classList.remove('dragover');
        handleFileSelect(e.dataTransfer.files);
    });
    
    function handleFileSelect(files) {
        Array.from(files).forEach(file => {
            if (file.type.startsWith('image/')) {
                addImageToGallery(file);
            }
        });
    }
    
    function addImageToGallery(file) {
        const reader = new FileReader();
        reader.onload = function(e) {
            const previewItem = createGalleryPreviewItem(e.target.result, file.name);
            previewContainer.appendChild(previewItem);
        };
        reader.readAsDataURL(file);
    }
    
    function createGalleryPreviewItem(src, filename) {
        const div = document.createElement('div');
        div.className = 'gallery-preview-item';
        div.innerHTML = `
            <img src="${src}" alt="${filename}">
            <button type="button" class="remove-btn" onclick="removeGalleryItem(this)">
                <i class="bi bi-x"></i>
            </button>
        `;
        return div;
    }
}

// ----------------------------------------
// Rich Text Editor Integration
// ----------------------------------------
function initRichEditor() {
    const editorContainers = document.querySelectorAll('.rich-editor-container');
    
    editorContainers.forEach(container => {
        const toolbar = container.querySelector('.rich-editor-toolbar');
        const content = container.querySelector('.rich-editor-content');
        const hiddenInput = container.querySelector('input[type="hidden"]');
        
        if (!toolbar || !content) return;
        
        // Make content editable
        content.contentEditable = true;
        
        // Toolbar buttons
        const buttons = {
            bold: () => document.execCommand('bold', false, null),
            italic: () => document.execCommand('italic', false, null),
            underline: () => document.execCommand('underline', false, null),
            strikethrough: () => document.execCommand('strikethrough', false, null),
            insertUnorderedList: () => document.execCommand('insertUnorderedList', false, null),
            insertOrderedList: () => document.execCommand('insertOrderedList', false, null),
            justifyLeft: () => document.execCommand('justifyLeft', false, null),
            justifyCenter: () => document.execCommand('justifyCenter', false, null),
            justifyRight: () => document.execCommand('justifyRight', false, null),
            removeFormat: () => document.execCommand('removeFormat', false, null)
        };
        
        // Add click handlers to toolbar buttons
        Object.keys(buttons).forEach(command => {
            const button = toolbar.querySelector(`[data-command="${command}"]`);
            if (button) {
                button.addEventListener('click', (e) => {
                    e.preventDefault();
                    buttons[command]();
                    content.focus();
                });
            }
        });
        
        // Update hidden input on content change
        content.addEventListener('input', function() {
            if (hiddenInput) {
                hiddenInput.value = this.innerHTML;
            }
        });
        
        // Handle paste to strip formatting
        content.addEventListener('paste', function(e) {
            e.preventDefault();
            const text = e.clipboardData.getData('text/plain');
            document.execCommand('insertText', false, text);
        });
    });
}

// ----------------------------------------
// Wireframe Interactions
// ----------------------------------------
function initWireframeInteractions() {
    // Handle image placeholder clicks only
    const imagePlaceholders = document.querySelectorAll('.wireframe-image-placeholder');
    
    imagePlaceholders.forEach(placeholder => {
        // Skip if already has click handler
        if (placeholder.dataset.imageHandler) return;
        placeholder.dataset.imageHandler = 'true';
        
        placeholder.addEventListener('click', function(e) {
            // Don't trigger if clicking on an existing input
            if (e.target.tagName === 'INPUT') return;
            
            // Check if file input already exists
            if (this.querySelector('input[type="file"]')) {
                this.querySelector('input[type="file"]').click();
            } else {
                const input = document.createElement('input');
                input.type = 'file';
                input.accept = 'image/*';
                input.style.display = 'none';
                
                this.appendChild(input);
                input.click();
                
                input.addEventListener('change', function(e) {
                    const file = e.target.files[0];
                    if (file && file.type.startsWith('image/')) {
                        const reader = new FileReader();
                        reader.onload = function(e) {
                            const img = document.createElement('img');
                            img.src = e.target.result;
                            img.style.width = '100%';
                            img.style.height = '100%';
                            img.style.objectFit = 'cover';
                            placeholder.innerHTML = '';
                            placeholder.appendChild(img);
                        };
                        reader.readAsDataURL(file);
                    }
                });
            }
        });
    });
}

// ----------------------------------------
// Result Items Initialization
// ----------------------------------------
function initResultItems() {
    // Load existing data if editing
    const jsonInput = document.getElementById('result_items_json');
    const container = document.getElementById('result-items-container');
    
    if (jsonInput && jsonInput.value && container) {
        try {
            const items = JSON.parse(jsonInput.value);
            if (items.length > 0) {
                container.innerHTML = '';
                
                items.forEach((item, index) => {
                    const newItem = document.createElement('div');
                    newItem.className = 'result-item mb-2';
                    newItem.innerHTML = `
                        <div class="input-group">
                            <input type="text" class="form-control" name="result_items[]" value="${item}" placeholder="Nhập kết quả ${index + 1}">
                            <button type="button" class="btn btn-outline-danger" onclick="removeResultItem(this)">
                                <i class="bi bi-trash"></i>
                            </button>
                        </div>
                    `;
                    container.appendChild(newItem);
                });
            }
        } catch (e) {
            console.error('Error parsing result items:', e);
        }
    }
    
    // Add event listeners to all existing inputs for auto-update
    addInputListeners();
}

function addInputListeners() {
    const inputs = document.querySelectorAll('input[name="result_items[]"]');
    inputs.forEach(input => {
        // Remove existing listener to avoid duplicates
        input.removeEventListener('input', updateResultItemsJSON);
        input.removeEventListener('blur', updateResultItemsJSON);
        
        // Add fresh listeners
        input.addEventListener('input', updateResultItemsJSON);
        input.addEventListener('blur', updateResultItemsJSON);
    });
}

// ----------------------------------------
// Result Items Management
// ----------------------------------------
function addResultItem() {
    const container = document.getElementById('result-items-container');
    const newItem = document.createElement('div');
    newItem.className = 'result-item mb-2';
    newItem.innerHTML = `
        <div class="input-group">
            <input type="text" class="form-control" name="result_items[]" placeholder="Nhập kết quả ${container.children.length + 1}">
            <button type="button" class="btn btn-outline-danger" onclick="removeResultItem(this)">
                <i class="bi bi-trash"></i>
            </button>
        </div>
    `;
    container.appendChild(newItem);
    addInputListeners(); // Add listeners to the new input
    updateResultItemsJSON();
}

function removeResultItem(button) {
    const item = button.closest('.result-item');
    if (item) {
        item.remove();
        updateResultItemsJSON();
    }
}

function updateResultItemsJSON() {
    const inputs = document.querySelectorAll('input[name="result_items[]"]');
    const items = Array.from(inputs)
        .map(input => input.value.trim())
        .filter(value => value !== '');
    
    const jsonInput = document.getElementById('result_items_json');
    if (jsonInput) {
        jsonInput.value = JSON.stringify(items);
    }
}

// ----------------------------------------
// Utility Functions
// ----------------------------------------

// Generate URL-friendly slug
function generateSlug(text) {
    return text
        .toLowerCase()
        .trim()
        .replace(/[^\w\s-]/g, '')
        .replace(/[\s_-]+/g, '-')
        .replace(/^-+|-+$/g, '');
}

// Remove gallery item
function removeGalleryItem(button) {
    const item = button.closest('.gallery-preview-item');
    if (item) {
        item.remove();
    }
}

// Validate project form before submit
function validateProjectForm() {
    const title = document.getElementById('title');
    const slug = document.getElementById('slug');
    const category = document.getElementById('category');
    
    let isValid = true;
    let errors = [];
    
    if (!title.value.trim()) {
        errors.push('Tiêu đề dự án là bắt buộc');
        isValid = false;
    }
    
    if (!slug.value.trim()) {
        errors.push('Slug là bắt buộc');
        isValid = false;
    }
    
    if (!category.value) {
        errors.push('Vui lòng chọn danh mục');
        isValid = false;
    }
    
    if (!isValid) {
        alert('Vui lòng sửa các lỗi sau:\n' + errors.join('\n'));
        return false;
    }
    
    return true;
}