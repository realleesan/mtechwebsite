// ----------------------------------------
// Blog Form Initialization
// ----------------------------------------
function initBlogForm() {
    
    // Tab switching for blog form
    const tabButtons = document.querySelectorAll('.blog-form-tabs .nav-link');
    const tabPanes = document.querySelectorAll('.tab-pane');
    
    tabButtons.forEach(button => {
        button.addEventListener('click', function(e) {
            e.preventDefault();
            
            // Remove active class from all buttons and panes
            tabButtons.forEach(btn => btn.classList.remove('active'));
            tabPanes.forEach(pane => pane.classList.remove('active', 'show'));
            
            // Add active class to clicked button
            this.classList.add('active');
            
            // Show corresponding tab pane
            const targetId = this.getAttribute('data-bs-target') || this.getAttribute('href');
            const targetPane = document.querySelector(targetId);
            if (targetPane) {
                targetPane.classList.add('active', 'show');
            }
        });
    });
    
    // Auto-generate slug from title
    const titleInput = document.getElementById('title');
    const slugInput = document.getElementById('slug');
    
    if (titleInput && slugInput) {
        titleInput.addEventListener('input', function() {
            if (!slugInput.value || slugInput.dataset.autoGenerated === 'true') {
                const slug = generateSlug(this.value);
                slugInput.value = slug;
                slugInput.dataset.autoGenerated = 'true';
            }
        });
        
        slugInput.addEventListener('input', function() {
            this.dataset.autoGenerated = 'false';
        });
    }
    
    // Note: toggleRecruitmentTab removed - now using checkRecruitmentCategory() for checkboxes
    
    // Handle category checkbox changes for recruitment tab toggling
    const categoryCheckboxes = document.querySelectorAll('input[name="category_ids[]"]');
    categoryCheckboxes.forEach(checkbox => {
        checkbox.addEventListener('change', checkRecruitmentCategory);
        checkbox.addEventListener('change', handleCategoryHierarchyChange);
    });
}

// ----------------------------------------
// Gallery Upload Functionality
// ----------------------------------------
function initGalleryUpload() {
    const uploadArea = document.querySelector('.gallery-upload-area');
    const fileInput = document.getElementById('gallery-input');
    const previewContainer = document.querySelector('.gallery-preview');
    
    if (!uploadArea || !fileInput) return;
    
    // Click to upload
    uploadArea.addEventListener('click', function() {
        fileInput.click();
    });
    
    // File selection
    fileInput.addEventListener('change', function(e) {
        handleFileSelect(e.target.files);
    });
    
    // Drag and drop
    uploadArea.addEventListener('dragover', function(e) {
        e.preventDefault();
        this.classList.add('dragover');
    });
    
    uploadArea.addEventListener('dragleave', function(e) {
        e.preventDefault();
        this.classList.remove('dragover');
    });
    
    uploadArea.addEventListener('drop', function(e) {
        e.preventDefault();
        this.classList.remove('dragover');
        handleFileSelect(e.dataTransfer.files);
    });
    
    function handleFileSelect(files) {
        if (!previewContainer) return;
        
        Array.from(files).forEach(file => {
            if (file.type.startsWith('image/')) {
                const reader = new FileReader();
                reader.onload = function(e) {
                    const previewItem = createPreviewItem(e.target.result, file.name);
                    previewContainer.appendChild(previewItem);
                };
                reader.readAsDataURL(file);
            }
        });
    }
    
    function createPreviewItem(src, name) {
        const item = document.createElement('div');
        item.className = 'preview-item';
        item.innerHTML = `
            <img src="${src}" alt="${name}">
            <button type="button" class="remove-btn" onclick="this.parentElement.remove()">
                <i class="bi bi-x"></i>
            </button>
        `;
        return item;
    }
}

// ----------------------------------------
// Rich Text Editor
// ----------------------------------------
function initRichEditor() {
    const editorContainers = document.querySelectorAll('.rich-editor-container');
    
    editorContainers.forEach(container => {
        const toolbar = container.querySelector('.rich-editor-toolbar');
        const content = container.querySelector('.rich-editor-content');
        const hiddenInput = container.querySelector('input[type="hidden"]');
        
        if (!toolbar || !content) return;
        
        // Toolbar button handlers
        toolbar.addEventListener('click', function(e) {
            const button = e.target.closest('[data-command]');
            if (!button) return;
            
            e.preventDefault();
            const command = button.dataset.command;
            
            // Focus content area
            content.focus();
            
            // Execute command
            document.execCommand(command, false, null);
            
            // Update hidden input
            if (hiddenInput) {
                hiddenInput.value = content.innerHTML;
            }
        });
        
        // Update hidden input on content change
        content.addEventListener('input', function() {
            if (hiddenInput) {
                hiddenInput.value = this.innerHTML;
            }
        });
        
        // Initialize content from hidden input
        if (hiddenInput && hiddenInput.value) {
            content.innerHTML = hiddenInput.value;
        }
    });
}

