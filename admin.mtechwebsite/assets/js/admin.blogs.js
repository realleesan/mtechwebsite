document.addEventListener('DOMContentLoaded', function() {
    
    // ----------------------------------------
    // Initialize Blogs Module
    // ----------------------------------------
    initBlogForm();
    initGalleryUpload();
    initRichEditor();
    initMainImagePreview();
    
});

// ----------------------------------------
// Blog Form Initialization
// ----------------------------------------
function initBlogForm() {
    
    // Tab switching for blog form
    const tabButtons = document.querySelectorAll('.blog-form-tabs .nav-link');
    const tabPanes = document.querySelectorAll('.tab-pane');
    
    tabButtons.forEach(button => {
        button.addEventListener('click', function(e) {
            e.preventDefault();
            
            // Remove active class from all buttons and panes
            tabButtons.forEach(btn => btn.classList.remove('active'));
            tabPanes.forEach(pane => pane.classList.remove('active', 'show'));
            
            // Add active class to clicked button
            this.classList.add('active');
            
            // Show corresponding tab pane
            const targetId = this.getAttribute('data-bs-target') || this.getAttribute('href');
            const targetPane = document.querySelector(targetId);
            if (targetPane) {
                targetPane.classList.add('active', 'show');
            }
        });
    });
    
    // Auto-generate slug from title
    const titleInput = document.getElementById('title');
    const slugInput = document.getElementById('slug');
    
    if (titleInput && slugInput) {
        titleInput.addEventListener('input', function() {
            if (!slugInput.value || slugInput.dataset.autoGenerated === 'true') {
                const slug = generateSlug(this.value);
                slugInput.value = slug;
                slugInput.dataset.autoGenerated = 'true';
            }
        });
        
        slugInput.addEventListener('input', function() {
            this.dataset.autoGenerated = 'false';
        });
    }
    
    // Toggle recruitment tab based on category selection
    const categorySelect = document.getElementById('category_id');
    if (categorySelect) {
        categorySelect.addEventListener('change', toggleRecruitmentTab);
        // Initialize on page load
        toggleRecruitmentTab();
    }
}

// ----------------------------------------
// Gallery Upload Functionality
// ----------------------------------------
function initGalleryUpload() {
    const uploadArea = document.querySelector('.gallery-upload-area');
    const fileInput = document.getElementById('gallery-input');
    const previewContainer = document.querySelector('.gallery-preview');
    
    if (!uploadArea || !fileInput) return;
    
    // Click to upload
    uploadArea.addEventListener('click', function() {
        fileInput.click();
    });
    
    // File selection
    fileInput.addEventListener('change', function(e) {
        handleFileSelect(e.target.files);
    });
    
    // Drag and drop
    uploadArea.addEventListener('dragover', function(e) {
        e.preventDefault();
        this.classList.add('dragover');
    });
    
    uploadArea.addEventListener('dragleave', function(e) {
        e.preventDefault();
        this.classList.remove('dragover');
    });
    
    uploadArea.addEventListener('drop', function(e) {
        e.preventDefault();
        this.classList.remove('dragover');
        handleFileSelect(e.dataTransfer.files);
    });
    
    function handleFileSelect(files) {
        if (!previewContainer) return;
        
        Array.from(files).forEach(file => {
            if (file.type.startsWith('image/')) {
                const reader = new FileReader();
                reader.onload = function(e) {
                    const previewItem = createPreviewItem(e.target.result, file.name);
                    previewContainer.appendChild(previewItem);
                };
                reader.readAsDataURL(file);
            }
        });
    }
    
    function createPreviewItem(src, name) {
        const item = document.createElement('div');
        item.className = 'preview-item';
        item.innerHTML = `
            <img src="${src}" alt="${name}">
            <button type="button" class="remove-btn" onclick="this.parentElement.remove()">
                <i class="bi bi-x"></i>
            </button>
        `;
        return item;
    }
}

// ----------------------------------------
// Rich Text Editor
// ----------------------------------------
function initRichEditor() {
    const editorContainers = document.querySelectorAll('.rich-editor-container');
    
    editorContainers.forEach(container => {
        const toolbar = container.querySelector('.rich-editor-toolbar');
        const content = container.querySelector('.rich-editor-content');
        const hiddenInput = container.querySelector('input[type="hidden"]');
        
        if (!toolbar || !content) return;
        
        // Toolbar button handlers
        toolbar.addEventListener('click', function(e) {
            const button = e.target.closest('[data-command]');
            if (!button) return;
            
            e.preventDefault();
            const command = button.dataset.command;
            
            // Focus content area
            content.focus();
            
            // Execute command
            document.execCommand(command, false, null);
            
            // Update hidden input
            if (hiddenInput) {
                hiddenInput.value = content.innerHTML;
            }
        });
        
        // Update hidden input on content change
        content.addEventListener('input', function() {
            if (hiddenInput) {
                hiddenInput.value = this.innerHTML;
            }
        });
        
        // Initialize content from hidden input
        if (hiddenInput && hiddenInput.value) {
            content.innerHTML = hiddenInput.value;
        }
    });
}

// ----------------------------------------
// Remove Current Image (for edit page)
// ----------------------------------------
function removeCurrentImage() {
    const currentImage = document.getElementById('currentImage');
    const removeFlag = document.getElementById('removeImageFlag');
    
    if (currentImage && removeFlag) {
        currentImage.style.display = 'none';
        removeFlag.value = '1';
        
        // Hide remove button
        const removeBtn = currentImage.parentElement.querySelector('button');
        if (removeBtn) removeBtn.style.display = 'none';
        
        // Show message
        const message = document.createElement('div');
        message.className = 'alert alert-warning alert-sm mt-2';
        message.innerHTML = '<i class="bi bi-exclamation-triangle me-1"></i>Ảnh sẽ được xóa khi lưu';
        currentImage.parentElement.appendChild(message);
    }
}

// ----------------------------------------
// Main Image Preview
// ----------------------------------------
function initMainImagePreview() {
    const imageInput = document.getElementById('image');
    const preview = document.getElementById('image-preview');
    const removeFlag = document.getElementById('removeImageFlag');
    
    if (!imageInput || !preview) return;
    
    imageInput.addEventListener('change', function(e) {
        const file = e.target.files[0];
        if (file && file.type.startsWith('image/')) {
            const reader = new FileReader();
            reader.onload = function(e) {
                preview.src = e.target.result;
                preview.style.display = 'block';
                
                // Reset remove flag when new image selected
                if (removeFlag) {
                    removeFlag.value = '0';
                }
            };
            reader.readAsDataURL(file);
        } else {
            preview.style.display = 'none';
        }
    });
}


// ----------------------------------------
// Toggle Recruitment Tab
// ----------------------------------------
function toggleRecruitmentTab() {
    const categorySelect = document.getElementById('category_id');
    const recruitmentTabNav = document.getElementById('recruitment-tab-nav');
    
    if (!categorySelect || !recruitmentTabNav) return;
    
    // Giả sử category tuyển dụng có ID = 7 (dựa vào ảnh bạn gửi)
    if (categorySelect.value == '7') {
        recruitmentTabNav.style.display = 'block';
    } else {
        recruitmentTabNav.style.display = 'none';
        // Reset recruitment tab if it was active
        const recruitmentTab = document.getElementById('recruitment-tab');
        if (recruitmentTab && recruitmentTab.classList.contains('active')) {
            const basicTab = document.getElementById('basic-tab');
            if (basicTab) basicTab.click();
        }
    }
}

// ----------------------------------------
// Generate Meta Suggestions
// ----------------------------------------
function generateMetaTitle() {
    const title = document.getElementById('title');
    const metaTitle = document.getElementById('meta_title');
    
    if (title && metaTitle && title.value) {
        metaTitle.value = title.value + ' - MTech';
    }
}

function generateMetaDescription() {
    const excerpt = document.getElementById('excerpt');
    const metaDescription = document.getElementById('meta_description');
    
    if (excerpt && metaDescription && excerpt.value) {
        metaDescription.value = excerpt.value.substring(0, 160);
    }
}

function generateMetaKeywords() {
    const tags = document.getElementById('tags');
    const metaKeywords = document.getElementById('meta_keywords');
    
    if (tags && metaKeywords && tags.value) {
        metaKeywords.value = tags.value;
    }
}

// ----------------------------------------
// Utility Functions
// ----------------------------------------
function generateSlug(text) {
    return text.toLowerCase()
        .replace(/[àáạảãâầấậẩẫăằắặẳẵ]/g, 'a')
        .replace(/[èéẹẻẽêềếệểễ]/g, 'e')
        .replace(/[ìíịỉĩ]/g, 'i')
        .replace(/[òóọỏõôồốộổỗơờớợởỡ]/g, 'o')
        .replace(/[ùúụủũưừứựửữ]/g, 'u')
        .replace(/[ỳýỵỷỹ]/g, 'y')
        .replace(/đ/g, 'd')
        .replace(/[^a-z0-9\s-]/g, '')
        .replace(/\s+/g, '-')
        .replace(/-+/g, '-')
        .trim('-');
}

// ----------------------------------------
// Form Validation
// ----------------------------------------
function validateBlogForm() {
    const title = document.getElementById('title');
    const slug = document.getElementById('slug');
    const categoryId = document.getElementById('category_id');
    
    if (!title || !title.value.trim()) {
        alert('Vui lòng nhập tiêu đề tin tức');
        if (title) title.focus();
        return false;
    }
    
    if (!slug || !slug.value.trim()) {
        alert('Vui lòng nhập slug');
        if (slug) slug.focus();
        return false;
    }
    
    if (!categoryId || !categoryId.value) {
        alert('Vui lòng chọn danh mục');
        if (categoryId) categoryId.focus();
        return false;
    }
    
    // Update rich editor content to hidden input
    const richEditorContent = document.querySelector('.rich-editor-content');
    const contentInput = document.querySelector('input[name="content"]');
    if (richEditorContent && contentInput) {
        contentInput.value = richEditorContent.innerHTML;
    }
    
    return true;
}

function validateCategoryForm() {
    const name = document.getElementById('name');
    const slug = document.getElementById('slug');
    
    if (!name || !name.value.trim()) {
        alert('Vui lòng nhập tên danh mục');
        if (name) name.focus();
        return false;
    }
    
    if (!slug || !slug.value.trim()) {
        alert('Vui lòng nhập slug');
        if (slug) slug.focus();
        return false;
    }
    
    return true;
}

// ----------------------------------------
// Loading States
// ----------------------------------------
function setButtonLoading(button, loading = true) {
    if (loading) {
        button.classList.add('loading');
        button.disabled = true;
    } else {
        button.classList.remove('loading');
        button.disabled = false;
    }
}

// ----------------------------------------
// Toast Notifications (if needed)
// ----------------------------------------
function showToast(message, type = 'success') {
    // Simple toast implementation
    const toast = document.createElement('div');
    toast.className = `alert alert-${type} position-fixed`;
    toast.style.cssText = 'top: 20px; right: 20px; z-index: 9999; min-width: 300px;';
    toast.innerHTML = `
        ${message}
        <button type="button" class="btn-close" onclick="this.parentElement.remove()"></button>
    `;
    
    document.body.appendChild(toast);
    
    // Auto remove after 5 seconds
    setTimeout(() => {
        if (toast.parentElement) {
            toast.remove();
        }
    }, 5000);
}